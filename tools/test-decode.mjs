import fs from 'node:fs';
import { readContainer, inflate, decodeBody } from '../js/decoder.js';
import { parseChampions } from '../js/champions.js';
const file = fs.readFileSync(process.argv[2]);
const champs = parseChampions(fs.readFileSync(new URL('../data/champions.tsv', import.meta.url), 'utf8'));
const t0 = Date.now();
const c = readContainer(file.buffer.slice(file.byteOffset, file.byteOffset + file.length));
console.log('header', c.strings, 'png', c.png.length, 'gz at', c.gzipOffset);
const body = await inflate(file, c.gzipOffset);
console.log('body', body.length, Date.now() - t0, 'ms');
const db = decodeBody(body, Object.keys(champs), (s, f) => {});
console.log('decoded in', Date.now() - t0, 'ms');
console.log('date', db.date, 'leagues', db.leagues.length, 'teams', db.teams.length, 'athletes', db.athletes.length, 'games', db.games.length);
console.log('warnings', db.warnings.length, db.warnings.slice(0, 5));
const a = db.athletes;
console.log('bad', a.filter(x => x.bad).length, 'noage', a.filter(x => x.age == null).length, 'noprof', a.filter(x => !Object.keys(x.prof || {}).length).length, 'noseason', a.filter(x => !(x.season||[]).length).length);
console.log(JSON.stringify(a[0]).slice(0, 600));
const g = db.games;
const np = g.reduce((s, x) => s + x.players.flat().filter(Boolean).length, 0);
console.log('players mapped', np, 'of', g.length * 10);
console.log(JSON.stringify(g[0]).slice(0, 800));
fs.writeFileSync('/tmp/w/db.json', JSON.stringify(db));
console.log('json size', fs.statSync('/tmp/w/db.json').size);
